// Turns data/coaches2026.json into fm/06a-coach-data.js: each club's real staff by game post, with
// game ratings estimated from the coach's playing record and age. Usage: node tools/build_coaches.js
// Posts come from the club's own coaching page where it could be read (OFFICIAL). Otherwise the KBO
// registered list is sorted into posts by playing position and record, and marked guess.
const fs = require('fs'), path = require('path');
const data = require('../data/coaches2026.json');
const OFFICIAL = { // club homepage, read 2026-11-09
  KT: {head: '김태한', pit: '제춘모', pen: '전병두', bat: '유한준', fld: '박기혁', run: '최만호', bat2: '장재중', ana: '김호', fut: '김태균'},
  두산: {head: '홍원기', pit: '정재훈', pen: '가득염', bat: '이진영', fld: '손지환', run: '고토', bat2: '조인성', ana: '손시헌', cond: '천종민', fut: '니무라'},
  LG: {head: '김정준', pit: '장진용', bat: '송지만', fld: '윤진호', run: '정수성', bat2: '최경철', ana: '김일경'},
  키움: {head: '강병식', pit: '김수경', pen: '박승주', bat: '장영석', fld: '문찬종', run: '김준완', bat2: '박도현', fut: '오윤'},
};
const KNOWN_HEAD = {NC: '서재응', 삼성: '최일언', 롯데: '강석천'};  // club page or club announcement
const MAIN = {head: 'tac', pit: 'lead', pen: 'man', bat: 'lead', fld: 'lead', run: 'tac', bat2: 'ana', cond: 'man', ana: 'ana', fut: 'lead'};
const clamp = (x, a, b) => Math.max(a, Math.min(b, x));
const YEAR = 2026;
function value(c) { const r = c.rec, t = r && r.totals; if (!t || !t.G) return 0.35;
  if (r.isP) return clamp(0.15 + ((t.W || 0) + 0.7 * (t.SV || 0) + 0.3 * (t.HLD || 0)) / 240 + (4.6 - (t.ERA || 5)) / 6 * Math.min(1, (t.IP || 0) / 300), 0, 1);
  return clamp(0.15 + (t.H || 0) / 2400 + (t.HR || 0) / 450 + (t.SB || 0) / 900 + ((t.AVG || 0.22) - 0.25) * 1.5 * Math.min(1, (t.AB || 0) / 1500), 0, 1); }
function rate(c, role, guess) {
  const v = value(c), t = (c.rec && c.rec.totals) || {}, pos = (c.rec && c.rec.pos) || '', age = c.birth ? YEAR - +c.birth.slice(0, 4) : 52, yrs = t.years || 0;
  const bb9 = t.IP ? t.BB * 9 / t.IP : 4, k9 = t.IP ? t.SO * 9 / t.IP : 6, r0 = x => clamp(Math.round(x), 1, 20);
  const a = {lead: r0(8 + v * 9 + (age >= 55 ? 1 : 0)),
    tac: r0(8 + v * 5 + (pos === '내야수' || pos === '포수' ? 1.5 : 0) + Math.min(3, (t.SB || 0) / 120)),
    ana: r0(8 + v * 4 + (pos === '포수' ? 4 : 0) + (c.rec && c.rec.isP && bb9 < 3.2 ? 2 : 0)),
    mot: r0(8 + v * 3 + Math.min(6, yrs / 3)),
    man: r0(8 + Math.min(5, (age - 40) / 3) + (c.rec && c.rec.isP ? 1 : 0) + v * 3)};
  const q = a[MAIN[role]];
  let spec = null;
  if (role === 'bat' && t.AB) spec = t.HR / t.AB > 0.03 ? '장타력' : t.AVG >= 0.285 ? '컨택' : '선구안';
  if ((role === 'pit' || role === 'pen') && t.IP) spec = role === 'pen' ? (t.SV >= 50 ? '마무리 육성' : '연투 관리') : bb9 < 3 ? '제구 교정' : k9 >= 7 ? '구위 향상' : '변화구';
  if (role === 'run' && t.SB >= 150) spec = '도루';
  const o = {n: c.n, q, a, age, pos, bio: bio(c)}; if (spec) o.spec = spec; if (guess) o.guess = 1; return o;
}
function bio(c) { const r = c.rec, t = r && r.totals; if (!t || !t.G) return '';
  return r.isP ? `통산 ${t.G}경기 ${t.W}승 ${t.SV}세이브 ERA ${t.ERA}` : `통산 ${t.G}경기 타율 ${t.AVG.toFixed(3).slice(1)} ${t.HR}홈런 ${t.SB}도루`; }
function guessPosts(list, head) { const out = {}, pool = list.filter(c => !c.mgr).slice();
  const take = (f, key) => { const i = pool.findIndex(f); if (i < 0) return; out[key] = pool.splice(i, 1)[0]; };
  const age = c => +(c.birth || '1975').slice(0, 4), byAge = () => pool.sort((a, b) => age(a) - age(b));
  if (head) take(c => c.n === head, 'head'); else { byAge(); take(c => c.rec && !c.rec.isP, 'head'); }
  byAge(); take(c => c.rec && c.rec.isP, 'pit'); take(c => c.rec && c.rec.isP, 'pen'); take(c => c.rec && c.rec.pos === '포수', 'bat2');
  if (!out.bat2) take(c => !c.rec, 'bat2');  // a coach with no KBO playing record, usually a hired specialist
  pool.sort((a, b) => ((b.rec && b.rec.totals.SB) || 0) - ((a.rec && a.rec.totals.SB) || 0)); take(c => c.rec && !c.rec.isP, 'run');
  pool.sort((a, b) => ((b.rec && (b.rec.totals.H || 0) + 3 * (b.rec.totals.HR || 0)) || 0) - ((a.rec && (a.rec.totals.H || 0) + 3 * (a.rec.totals.HR || 0)) || 0)); take(c => c.rec && !c.rec.isP, 'bat');
  take(c => c.rec && c.rec.pos === '내야수', 'fld'); if (!out.fld) take(c => c.rec && !c.rec.isP, 'fld');
  return out; }
const db = {}, extra = data.extra || {};
for (const t in data.teams) { const list = data.teams[t].coaches, off = OFFICIAL[t]; db[t] = {};
  if (off) { for (const r in off) { const c = list.find(x => x.n === off[r]) || extra[off[r]] || {n: off[r]}; db[t][r] = rate(c, r, false); } }
  else { const g = guessPosts(list, KNOWN_HEAD[t]); for (const r in g) db[t][r] = rate(g[r], r, r !== 'head' || !KNOWN_HEAD[t]); } }
const names = {고토: '고토 코지', 니무라: '니무라 토오루'};
for (const t in db) for (const r in db[t]) if (names[db[t][r].n]) db[t][r].n = names[db[t][r].n];
const body = `// Generated by tools/build_coaches.js from the clubs' coaching pages and the KBO register (2026). Ratings are game\n// estimates from each coach's playing record and age. guess: the post is inferred, the club's page could not be read.\nconst COACH_DB=${JSON.stringify(db)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'fm', '06a-coach-data.js'), body);
for (const t in db) console.log(t, Object.entries(db[t]).map(([r, c]) => `${r}:${c.n}(${c.q})${c.guess ? '?' : ''}`).join(' '));

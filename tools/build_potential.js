// Growth trend for every player with a 2024-25 KBO record, from public stats, for the potential rule in fm/00-core.js.
// usage: node tools/build_potential.js        writes fm/08b-potential-data.js (then run node tools/build_fm.js)
//        node tools/build_potential.js --report   also writes data/ratings-review.csv: one row per rated player
//                                               with age, OVR, potential, trend and review flags
// Trend (rating points, -4..+4): 2026 against the PA/IP-weighted 2024-25 level, shrunk toward 0 by sample size.
//   hitters  wOBA-like = (.7*(BB+HBP) + .9*1B + 1.25*2B + 1.6*3B + 2.0*HR) / PA     .015 = 1 point
//   pitchers FIP-like  = (13*HR + 3*(BB+HBP) - 2*SO) / IP (lower is better)        .40  = 1 point
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const career = require(path.join(ROOT, 'data', 'career.json'));
const kbo = require(path.join(ROOT, 'data', 'kbo2026.json'));
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
const ip = s => { const m = String(s).trim().match(/^(\d+)(?:\s+(\d)\/3)?$/); return m ? +m[1] + (m[2] ? +m[2] / 3 : 0) : +s || 0; };

const now = {}; // name -> {t, rate, n}
for (const [, rows] of Object.entries(kbo.tables.hit)) for (const r of rows) {
  const c = r.cells, [PA, , H, d2, d3, HR] = [+c[5], +c[6], +c[7], +c[8], +c[9], +c[10]], BB = +c[14], HBP = +c[15];
  if (PA > 0) now[c[1]] = {t: 'B', n: PA, rate: (.7 * (BB + HBP) + .9 * (H - d2 - d3 - HR) + 1.25 * d2 + 1.6 * d3 + 2 * HR) / PA};
}
for (const [, rows] of Object.entries(kbo.tables.pit)) for (const r of rows) {
  const c = r.cells, IP = ip(c[13]), HR = +c[15], BB = +c[16], HBP = +c[17], SO = +c[18];
  if (IP > 0) now[c[1]] = {t: 'P', n: IP, rate: (13 * HR + 3 * (BB + HBP) - 2 * SO) / IP};
}
function before(name, t) {
  const c = career[name]; if (!c || c.t !== t) return null; let n = 0, s = 0;
  for (const y of c.y) { if (y[0] < 2024) continue;
    if (t === 'B') { const [, , , PA, , , H, d2, d3, HR, , , , BB, HBP] = y; if (!PA) continue;
      s += .7 * (BB + HBP) + .9 * (H - d2 - d3 - HR) + 1.25 * d2 + 1.6 * d3 + 2 * HR; n += PA; }
    else { const IP = y[7] / 3, HR = y[9], BB = y[10], HBP = y[11], SO = y[12]; if (!IP) continue; s += 13 * HR + 3 * (BB + HBP) - 2 * SO; n += IP; } }
  return n ? {n, rate: s / n} : null;
}
const TREND = {};
for (const [name, x] of Object.entries(now)) {
  const b = before(name, x.t); if (!b) continue;
  const full = x.t === 'B' ? 400 : 100, rel = Math.min(1, x.n / full) * Math.min(1, b.n / full);
  const raw = x.t === 'B' ? (x.rate - b.rate) / .015 : (b.rate - x.rate) / .40;
  const v = Math.round(clamp(raw * rel, -4, 4));
  if (v) TREND[name] = v;
}
const out = `
// ---------- growth trend (generated by tools/build_potential.js from KBO 2024-26 public records) ----------
// name -> rating points, + = 2026 better than 2024-25. Feeds potentialOf() in fm/00-core.js.
const TREND_2026=${JSON.stringify(TREND)};
`;
fs.writeFileSync(path.join(ROOT, 'fm', '08b-potential-data.js'), out);
console.log('trend for', Object.keys(TREND).length, 'players; up', Object.values(TREND).filter(v => v > 0).length, 'down', Object.values(TREND).filter(v => v < 0).length);

if (process.argv.includes('--report')) {
  // the same rule as potentialOf() in fm/00-core.js, kept in step by the test in tools/tests/potential.js
  const {potentialRule} = require(path.join(ROOT, 'tools', 'tests', 'potential-rule.js'));
  const csv = fs.readFileSync(path.join(ROOT, 'data', 'players2026.csv'), 'utf8').replace(/^﻿/, '').trim().split(/\r?\n/);
  const head = csv.shift().split(','), ix = k => head.indexOf(k);
  const rows = [['team', 'name', 'type', 'pos', 'age', 'ovr', 'pot', 'room', 'trend', 'flags'].join(',')];
  for (const line of csv) { const c = line.split(','), age = +c[ix('age')], ovr = +c[ix('ovr')], name = c[ix('name')];
    const r = potentialRule({name, age, ovr, trend: TREND[name] || 0, round: null});
    const flags = [];
    if (age >= 34 && ovr >= 78) flags.push('고령 고평가');
    if (age <= 24 && r.pot - ovr >= 14) flags.push('큰 성장폭');
    if ((TREND[name] || 0) <= -3) flags.push('하락세');
    if ((TREND[name] || 0) >= 3) flags.push('상승세');
    if (+c[ix('PA/TBF')] < 30) flags.push('표본 적음');
    rows.push([c[ix('team')], name, c[ix('type')], c[ix('pos/role')], age, ovr, r.pot, r.pot - ovr, TREND[name] || 0, flags.join(' / ')].join(','));
  }
  fs.writeFileSync(path.join(ROOT, 'data', 'ratings-review.csv'), '﻿' + rows.join('\n') + '\n');
  console.log('data/ratings-review.csv:', rows.length - 1, 'players,', rows.filter(r => /고령|성장폭|하락세|상승세/.test(r)).length, 'flagged');
}

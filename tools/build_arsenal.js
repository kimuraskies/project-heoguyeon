// Merge data/arsenal-mlb.json (tracked MLB/AAA mixes) and data/arsenal-kbo.txt (KBO pitchers by description)
// into the ARSENAL table in core.js.  Usage: node tools/build_arsenal.js
// Entry format: name -> "FF45 CH25 SL15 CU15|m"  (m = MLB/AAA pitch tracking, k = KBO repertoire by description)
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const GAME = ['FF', 'SI', 'SL', 'CU', 'CH', 'FS', 'FC', 'SW', 'SP'];
// MLB Statcast codes -> game codes (sweeper ST -> SW, slurve SV -> SL, knuckle curve KC -> CU, MLB splitter FS -> SP)
const MLB = {FF: 'FF', SI: 'SI', FT: 'SI', SL: 'SL', ST: 'SW', SV: 'SL', CU: 'CU', KC: 'CU', CS: 'CU', CH: 'CH', SC: 'CH', FS: 'SP', FO: 'FS', FC: 'FC'};
const out = {};
function put(name, list, src) {
  const m = new Map();
  for (const [c, v] of list) if (GAME.includes(c) && v > 0) m.set(c, (m.get(c) || 0) + v);
  const keep = [...m].filter(([, v]) => v >= 3).sort((a, b) => b[1] - a[1]);
  const sum = keep.reduce((s, [, v]) => s + v, 0);
  if (keep.length < 2) throw new Error(name + ': fewer than 2 pitches');
  out[name] = keep.map(([c, v]) => c + Math.round(v / sum * 100)).join(' ') + '|' + src;
}
for (const [name, v] of Object.entries(JSON.parse(fs.readFileSync(path.join(root, 'data/arsenal-mlb.json'), 'utf8')))) {
  if (v) put(name, v.pitches.map(([c, s]) => [MLB[c], s * 100]), 'm');
}
for (const line of fs.readFileSync(path.join(root, 'data/arsenal-kbo.txt'), 'utf8').split(/\r?\n/)) {
  const t = line.trim(); if (!t || t[0] === '#') continue;
  const [name, ...ps] = t.split(/\s+/);
  if (out[name]) throw new Error(name + ' is in both sources');
  put(name, ps.map(p => { const m = p.match(/^([A-Z]{2})(\d+)$/); if (!m) throw new Error(name + ': bad token ' + p); return [m[1], +m[2]]; }), 'k');
}
const f = path.join(root, 'core.js');
let s = fs.readFileSync(f, 'utf8');
const line = 'var ARSENAL = ' + JSON.stringify(out) + '; // real pitch mixes, generated by tools/build_arsenal.js';
const re = /^var ARSENAL = .*$/m;
if (re.test(s)) s = s.replace(re, () => line);
else { const at = s.indexOf('function statSeed('); if (at < 0) throw new Error('no anchor'); s = s.slice(0, at) + line + '\n' + s.slice(at); }
fs.writeFileSync(f, s);
console.log(Object.keys(out).length + ' pitchers: ' + Object.values(out).filter(v => v.endsWith('|m')).length + ' tracked, ' + Object.values(out).filter(v => v.endsWith('|k')).length + ' by description');
